        .ddr_ck_p(ddr_ck_p),.ddr_ck_n(ddr_ck_n),
        .ddr_dm(ddr_dm),.ddr_dq(ddr_dq),
        .ddr_dqs_p(ddr_dqs_p),.ddr_dqs_n(ddr_dqs_n)
    );
